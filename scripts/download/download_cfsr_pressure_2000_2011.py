gz_files = [
    url for url in filelist
    if url.lower().endswith(".gz")
]

if not gz_files:
    raise ValueError(
        "No .gz climate files were found in the GDEX file list."
    )

print("=" * 72)
print("CFSR PRESSURE DOWNLOAD")
print("=" * 72)

print(f"Total entries in GDEX list: {len(filelist):,}")
print(f"Climate .gz files found:   {len(gz_files):,}")
print(f"Destination:               {OUTPUT_DIR}")
print()


# ============================================================
# DOWNLOAD FILES
# ============================================================

downloaded = 0
skipped = 0
failed = []

for number, url in enumerate(gz_files, start=1):

    filename = Path(url).name
    output_path = OUTPUT_DIR / filename

    print(
        f"[{number:,}/{len(gz_files):,}] "
        f"{filename}",
        end=" ... ",
        flush=True
    )

    # Skip files that have already been downloaded.
    if output_path.exists() and output_path.stat().st_size > 0:
        print("already exists - skipped")
        skipped += 1
        continue

    try:

        response = requests.get(
            url,
            stream=True,
            timeout=120
        )

        response.raise_for_status()

        with open(output_path, "wb") as outfile:

            for chunk in response.iter_content(
                chunk_size=1024 * 1024
            ):

                if chunk:
                    outfile.write(chunk)

        print("done")
        downloaded += 1

    except requests.RequestException as error:

        print(f"FAILED: {error}")

        failed.append(
            {
                "filename": filename,
                "error": str(error)
            }
        )


# ============================================================
